import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  colors,
  fonts,
  focusRing,
  gradients,
  layout,
  motionTokens,
  radii,
  shadows,
  typeScale,
  type TypeStyle,
} from "../src/core/tokens.ts";

const kebab = (value: string) =>
  value.replace(/([a-z])([0-9])/g, "$1-$2").replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

const colorLines = Object.entries(colors).map(([key, value]) => `  --color-${kebab(key)}: ${value};`);
const rootColorLines = Object.entries(colors).map(([key, value]) => `  --${kebab(key)}: ${value};`);

const fontLines = [
  `  --font-serif: ${fonts.serif};`,
  `  --font-sans: ${fonts.sans};`,
  `  --font-mono: ${fonts.mono};`,
];

const radiusLines = Object.entries(radii).map(([key, value]) => `  --radius-${key}: ${value}px;`);

const shadowLines = Object.entries(shadows).map(([key, value]) => `  --shadow-${key}: ${value};`);

const themeBlock = [
  "@theme {",
  "  --color-*: initial;",
  ...colorLines,
  ...fontLines,
  "  --radius-*: initial;",
  ...radiusLines,
  "  --shadow-*: initial;",
  ...shadowLines,
  `  --ease-calm: ${motionTokens.easeCss};`,
  `  --breakpoint-md: ${layout.mobileBreakpoint}px;`,
  "}",
].join("\n");

const rootBlock = [
  ":root {",
  ...rootColorLines,
  `  --gradient-orb: ${gradients.orb};`,
  `  --gradient-mark: ${gradients.mark};`,
  `  --ease: ${motionTokens.easeCss};`,
  `  --focus-ring-width: ${focusRing.width}px;`,
  `  --focus-ring-offset: ${focusRing.offset}px;`,
  `  --container: ${layout.container}px;`,
  "}",
].join("\n");

const scaled = (px: number) => `calc(${px}px * var(--type-scale, 1))`;
const scaledLine = (line: number) =>
  `calc(${line}px * var(--type-scale, 1) + var(--devanagari-line-extra, 0px))`;

const fontVar = (family: TypeStyle["family"]) => `var(--font-${family})`;

function typeClass(name: string, style: TypeStyle) {
  const lines = [
    `  font-family: ${fontVar(style.family)};`,
    `  font-weight: ${style.weight};`,
    `  font-size: ${scaled(style.size)};`,
    `  line-height: ${scaledLine(style.line)};`,
    `  letter-spacing: ${style.tracking}em;`,
  ];
  if (style.uppercase) lines.push("  text-transform: uppercase;");
  if (style.color) lines.push(`  color: var(--${kebab(style.color)});`);
  return `.type-${name} {\n${lines.join("\n")}\n}`;
}

function mobileTypeClass(name: string, style: TypeStyle) {
  if (!style.mobileSize || !style.mobileLine) return null;
  return `  .type-${name} {\n    font-size: ${scaled(style.mobileSize)};\n    line-height: ${scaledLine(style.mobileLine)};\n  }`;
}

const typeClasses = Object.entries(typeScale).map(([name, style]) => typeClass(name, style));
const mobileClasses = Object.entries(typeScale)
  .map(([name, style]) => mobileTypeClass(name, style))
  .filter((block): block is string => block !== null);

function forcedMobileTypeClass(name: string, style: TypeStyle): string | null {
  if (!style.mobileSize || !style.mobileLine) return null;
  return `  .type-scale-mobile .type-${name} {\n    font-size: ${scaled(style.mobileSize)};\n    line-height: ${scaledLine(style.mobileLine)};\n  }`;
}

const forcedMobileClasses = Object.entries(typeScale)
  .map(([name, style]) => forcedMobileTypeClass(name, style))
  .filter((block): block is string => block !== null);

const typeBlock = [
  "@layer components {",
  ...typeClasses.map((block) => block.split("\n").map((line) => `  ${line}`).join("\n")),
  `  @media (max-width: ${layout.mobileBreakpoint - 1}px) {`,
  ...mobileClasses.map((block) => block.split("\n").map((line) => `  ${line}`).join("\n")),
  "  }",
  ...forcedMobileClasses,
  "}",
].join("\n");

const output = [
  "/* Generated by scripts/gen-theme.ts from src/core/tokens.ts. Do not edit. */",
  themeBlock,
  rootBlock,
  typeBlock,
  "",
].join("\n\n");

const target = resolve(dirname(fileURLToPath(import.meta.url)), "../src/web/styles/theme.generated.css");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, output);
console.log(`theme written to ${target}`);
